// @route   POST api/auth/enroll
// @desc    Enroll user in a course
// @access  Private
router.post('/enroll', auth, async (req, res) => {
    const { title } = req.body;

    try {
        let user = await User.findById(req.user.id).select('-password');
        if (!user) {
            return res.status(404).json({ message: 'User not found' });
        }

        // Check if already enrolled
        const alreadyEnrolled = user.enrolledCourses.some(c => c.title === title);
        if (alreadyEnrolled) {
            return res.status(400).json({ message: 'Already enrolled in this course' });
        }

        user.enrolledCourses.push({ title });
        await user.save();

        res.json(user);
    } catch (err) {
        console.error(err.message);
        res.status(500).send('Server Error');
    }
});

// @route   POST api/auth/bookmark
// @desc    Toggle bookmark for a course
// @access  Private
router.post('/bookmark', auth, async (req, res) => {
    const { title } = req.body;

    try {
        let user = await User.findById(req.user.id).select('-password');
        if (!user) {
            return res.status(404).json({ message: 'User not found' });
        }

        // Check if already bookmarked
        const bookmarkIndex = user.bookmarkedCourses.findIndex(c => c.title === title);

        if (bookmarkIndex > -1) {
            // Unbookmark
            user.bookmarkedCourses.splice(bookmarkIndex, 1);
        } else {
            // Bookmark
            user.bookmarkedCourses.push({ title });
        }

        await user.save();
        res.json(user);
    } catch (err) {
        console.error(err.message);
        res.status(500).send('Server Error');
    }
});

module.exports = router;
